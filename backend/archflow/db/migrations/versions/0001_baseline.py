# Earlier ArchFlow versions created their schema with SQL scripts (SQLite: CREATE TABLE IF NOT EXISTS on every
# start; Postgres: migrations/*.sql). This baseline converges any of those databases, and an empty one, onto the
# same schema: it creates what is missing, adds columns that older versions lacked, and applies the data fixes the
# old scripts made. Every step checks first, so it is safe to run on any of them.


def _insp():
    return sa.inspect(op.get_bind())


def _create(name: str, *columns, **kw) -> None:
    if not _insp().has_table(name):
        op.create_table(name, *columns, **kw)


def _index(table: str, name: str, columns: list, unique: bool = False) -> None:
    if name not in {i["name"] for i in _insp().get_indexes(table)}:
        op.create_index(name, table, columns, unique=unique)


def _columns(table: str) -> set[str]:
    insp = _insp()
    return {c["name"] for c in insp.get_columns(table)} if insp.has_table(table) else set()


def _add(table: str, column: sa.Column) -> None:
    if _insp().has_table(table) and column.name not in _columns(table):
        with op.batch_alter_table(table) as batch:
            batch.add_column(column)


def _legacy_before() -> None:
    """Fixes that must run before the tables are created."""
    # Accounts (005): memberships used to be keyed by a display name that cannot be mapped to an account.
    if "user_name" in _columns("memberships"):
        op.drop_table("memberships")


